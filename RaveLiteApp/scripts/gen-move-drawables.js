#!/usr/bin/env node
/**
 * Writes one Android vector drawable per move glyph,
 * android/app/src/main/res/drawable/ic_move_<id>.xml, for notification
 * small icons. Status-bar icons are white shapes that Android tints, so
 * every stroke and head is drawn in white.
 *
 * Run after editing src/components/icons/moveGlyphs.json:
 *   node scripts/gen-move-drawables.js
 */
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const glyphs = require(path.join(root, 'src/components/icons/moveGlyphs.json'));
const outDir = path.join(root, 'android/app/src/main/res/drawable');

// Keep in step with src/components/icons/MoveIcon.tsx.
const STROKE = 2.6;
const LUCIDE_STROKE = 2.2;
const HEAD_RADIUS = 2.45;
const GROUND_SCALE = 0.62;
const GROUND_OPACITY = 0.5;

const num = x => String(Number(x.toFixed(3)));

const circle = (cx, cy, r) =>
  `M${num(cx - r)},${num(cy)}a${num(r)},${num(r)} 0 1,0 ${num(2 * r)},0` +
  `a${num(r)},${num(r)} 0 1,0 ${num(-2 * r)},0Z`;

function strokePath(d, width, alpha = 1) {
  return (
    `    <path\n        android:pathData="${d}"\n` +
    '        android:fillColor="#00000000"\n' +
    '        android:strokeColor="#FFFFFFFF"\n' +
    `        android:strokeWidth="${num(width)}"\n` +
    (alpha < 1 ? `        android:strokeAlpha="${alpha}"\n` : '') +
    '        android:strokeLineCap="round"\n' +
    '        android:strokeLineJoin="round" />'
  );
}

function shapes(glyph) {
  const width = glyph.lucide ? LUCIDE_STROKE : STROKE;
  return glyph.shapes.map(([kind, ...a]) => {
    switch (kind) {
      case 'head':
        return (
          `    <path\n        android:pathData="${circle(
            a[0],
            a[1],
            HEAD_RADIUS,
          )}"\n` + '        android:fillColor="#FFFFFFFF" />'
        );
      case 'ring':
        return strokePath(circle(a[0], a[1], a[2]), width);
      case 'line': {
        let d = `M${num(a[0])},${num(a[1])}`;
        for (let i = 2; i < a.length; i += 2) {
          d += `L${num(a[i])},${num(a[i + 1])}`;
        }
        return strokePath(d, width);
      }
      case 'path':
        return strokePath(a[0], width);
      case 'ground':
        return strokePath(
          `M${num(a[0])},${num(a[1])}L${num(a[2])},${num(a[3])}`,
          width * GROUND_SCALE,
          GROUND_OPACITY,
        );
      default:
        throw new Error(`Unknown shape "${kind}"`);
    }
  });
}

let written = 0;
for (const [id, glyph] of Object.entries(glyphs)) {
  const xml =
    '<?xml version="1.0" encoding="utf-8"?>\n' +
    '<!-- Generated by scripts/gen-move-drawables.js from moveGlyphs.json. Do not edit. -->\n' +
    '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n' +
    '    android:width="24dp"\n' +
    '    android:height="24dp"\n' +
    '    android:viewportWidth="24"\n' +
    '    android:viewportHeight="24">\n' +
    shapes(glyph).join('\n') +
    '\n</vector>\n';
  fs.writeFileSync(path.join(outDir, `ic_move_${id}.xml`), xml);
  written++;
}
console.log(`Wrote ${written} drawables to ${path.relative(root, outDir)}`);
